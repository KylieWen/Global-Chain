import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const base=process.env.REVIEW_BASE_URL??'http://127.0.0.1:3000';
const folder=resolve(process.env.REVIEW_OUTPUT_DIR??'output/qa/2026-10-23-navigation-rounds');
await mkdir(folder,{recursive:true});
const manifest=JSON.parse(await readFile('data/published/manifest.json','utf8'));
const browser=await chromium.launch({channel:process.env.CI?undefined:'chrome'});
const checks=[];const pageErrors=[];
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 page.on('pageerror',error=>pageErrors.push(error.message));
 for(const fixture of manifest.fixtures) {
  await page.goto(`${base}/products/${fixture.productId}`,{waitUntil:'networkidle'});
  const labels=await page.locator('.tree-node').evaluateAll(nodes=>nodes.filter(node=>node.querySelector('a')).map(node=>({item:node.querySelector('strong').textContent,label:node.querySelector('a').getAttribute('aria-label')})));
  assert.ok(labels.length>0);
  assert.ok(labels.every(({item,label})=>label?.includes(item)),fixture.productId);
  const nav=page.locator('.product-level-nav');
  assert.equal(await nav.locator('[aria-current="page"]').count(),1);
  const sizes=await nav.locator('a').evaluateAll(nodes=>nodes.map(node=>node.getBoundingClientRect().height));
  assert.ok(sizes.every(height=>height>=44));
  checks.push({product:fixture.productId,uniqueTreeLinkNames:labels.length,navigationMinHeight:Math.min(...sizes)});
 }
 await page.goto(`${base}/products/generic-smartphone/supply-chain`,{waitUntil:'networkidle'});
 const inactive=page.locator('.product-level-nav a:not([aria-current])').first();
 await page.mouse.move(0,0);
 const initial=await inactive.evaluate(node=>getComputedStyle(node).backgroundColor);
 await inactive.hover();
 await page.waitForTimeout(200);
 assert.notEqual(await inactive.evaluate(node=>getComputedStyle(node).backgroundColor),initial);
 const steps=page.locator('.step-card-collapsible');
 const next=steps.first().getByRole('link',{name:'下一步 →',exact:true});
 const targetId=(await next.getAttribute('href')).slice(1);
 await next.focus();await page.keyboard.press('Enter');
 await page.waitForFunction(id=>document.activeElement===document.getElementById(id)?.querySelector('summary'),targetId);
 assert.equal(await page.locator(`[id="${targetId}"]`).getAttribute('open'),'');
 assert.equal(new URL(page.url()).hash,`#${targetId}`);
 assert.equal(await page.locator(`[id="${targetId}"] > summary`).evaluate(node=>getComputedStyle(node).outlineStyle),'solid');
 await page.waitForFunction(id=>{
  const target=document.getElementById(id);
  const summary=target?.querySelector('summary');
  if(!summary)return false;
  const rect=summary.getBoundingClientRect();
  const header=document.querySelector('.site-header')?.getBoundingClientRect();
  const expectedTop=Math.max(parseFloat(getComputedStyle(target).scrollMarginTop)||0,header?.bottom??0);
  return rect.top>=(header?.bottom??0)&&rect.top<=expectedTop+4&&rect.bottom<=innerHeight;
 },targetId);
 await page.screenshot({path:resolve(folder,'keyboard-step-focus.png')});
 await page.goBack();
 assert.equal(new URL(page.url()).hash,'');
 checks.push({nextStepOpens:true,keyboardFocusAtTarget:true,targetVisibleBelowHeader:true,nativeHashHistory:true,navigationHover:true});
 await page.goto(`${base}/trade-guide`,{waitUntil:'networkidle'});
 const hint=page.locator('.action-hint').first();
 await page.mouse.move(0,0);await hint.getByRole('link').hover();
 await page.waitForTimeout(180);assert.equal(await page.getByRole('tooltip').count(),0);
 await page.getByRole('tooltip').waitFor();
 await page.keyboard.press('Escape');await page.getByRole('tooltip').waitFor({state:'detached'});
 checks.push({delayedExplanation:true,escapeDismisses:true});
 await page.mouse.move(0,0);
 await page.reload({waitUntil:'networkidle'});
 const keyboardToggle=page.locator('.hint-toggle').first();
 await keyboardToggle.focus();
 assert.equal(await keyboardToggle.getAttribute('aria-expanded'),'false');
 await page.keyboard.press('Enter');
 await page.getByRole('tooltip').waitFor();
 assert.equal(await keyboardToggle.getAttribute('aria-expanded'),'true');
 const describedBy=await keyboardToggle.getAttribute('aria-describedby');
 assert.equal(await page.getByRole('tooltip').getAttribute('id'),describedBy);
 checks.push({helpButtonKeyboardActivation:true,helpDescriptionAssociated:true});
 const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 mobile.on('pageerror',error=>pageErrors.push(error.message));
 await mobile.goto(`${base}/trade-guide`,{waitUntil:'networkidle'});
 const toggle=mobile.locator('.hint-toggle').first();
 assert.equal((await toggle.boundingBox()).height,44);
 await toggle.tap();await mobile.getByRole('tooltip').waitFor();
 const width=await mobile.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
 assert.ok(width.scroll<=width.client);
 await mobile.screenshot({path:resolve(folder,'mobile-guide-explanation.png')});
 checks.push({mobileHintTarget:44,mobileWidth:width});
 assert.deepEqual(pageErrors,[]);
 await writeFile(resolve(folder,'result.json'),JSON.stringify({base,time:new Date().toISOString(),checks,pageErrors},null,2));
 console.log(JSON.stringify({checks,pageErrors}));
}finally{await browser.close();}
